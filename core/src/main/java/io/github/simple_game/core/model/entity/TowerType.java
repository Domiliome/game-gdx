package io.github.simple_game.core.model.entity;

/**
 * Перечисление-каталог, определяющее доступные виды оборонительных сооружений.
 * Используется подсистемой магазина для динамической верстки интерфейса и проверки баланса золота.
 */
public enum TowerType {
    /**
     * Башня лучников. Эффективна против быстрых одиночных целей.
     */
    ARCHER(100),

    /**
     * Артиллерийская пушка. Идеальна против медленных бронированных врагов.
     */
    CANNON(250),

    /**
     * Магическая башня. Обладает большим радиусом поражения на карте.
     */
    MAGIC(200);

    private final int cost;

    /**
     * Инициализирует конфигурацию типа оборонительного сооружения для магазина.
     *
     * @param cost стоимость покупки и возведения башни на карте
     */
    TowerType(int cost) {
        this.cost = cost;
    }

    /**
     * @return количество золота, необходимое для покупки и постройки башни
     */
    public int getCost() { return cost; }
}
